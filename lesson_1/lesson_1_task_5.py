"""Задание: вывод телефонного номера по цифрам."""



def print_num(num):
    """
    Печатает переданный номер без перевода строки.

    :param num: число или строка для вывода
    :type num: int | str
    """
    print(num, end="")




def main():
    """Основная функция программы — собирает и выводит номер телефона."""
    # Список цифр телефонного номера (код и номер)
    phone_digits = [8, 8, 0, 0, 5, 5, 5, 3, 5, 3, 5]

    # Поочерёдно печатаем все цифры номера
    for digit in phone_digits:
        print_num(digit)

    # Завершаем вывод переводом строки
    print()




if __name__ == "__main__":
    main()
